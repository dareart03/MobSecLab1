package com.google.firebase.example.makeitso.data.credential

import android.content.Context
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CreatePasswordRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CredentialOption
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.GetCredentialResponse
import androidx.credentials.GetPasswordOption
import androidx.credentials.PasswordCredential
import androidx.credentials.exceptions.ClearCredentialException
import androidx.credentials.exceptions.CreateCredentialCancellationException
import androidx.credentials.exceptions.CreateCredentialException
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.google.firebase.example.makeitso.R

/** What the system credential dialog gave back. */
sealed interface CredentialResult {
    /** A password the user picked in the system dialog. */
    data class Password(val email: String, val password: String) : CredentialResult

    /** A Google ID token; it is passed to Firebase Auth. */
    data class Google(val idToken: String) : CredentialResult

    /** The user closed the dialog, or there was nothing to offer. Not an error. */
    data object Dismissed : CredentialResult

    data class Error(val message: String) : CredentialResult
}

/**
 * Thin wrapper over Credential Manager. The app never stores the password itself: it is only
 * handed to the system password manager (save) or received from it (sign in).
 *
 * [context] must be an Activity context, because Credential Manager shows system UI.
 */
class CredentialAuthClient(private val context: Context) {
    private val credentialManager = CredentialManager.create(context)

    // Generated by the Google Services plugin from google-services.json. It exists only when the
    // Google provider is enabled in Firebase and the file was downloaded afterwards.
    private val webClientId: String = context.getString(R.string.default_web_client_id)

    /** Offers to save the new account in the system password manager. */
    suspend fun savePassword(email: String, password: String) {
        try {
            credentialManager.createCredential(
                context,
                CreatePasswordRequest(id = email, password = password)
            )
        } catch (e: CreateCredentialCancellationException) {
            // The user declined to save: that's fine.
        } catch (e: CreateCredentialException) {
            // Saving is optional; never fail the sign-up because of it.
            Log.w(TAG, "Could not save password: ${e.type} ${e.errorMessage}")
        }
    }

    /**
     * ONE system dialog that offers both the saved password(s) and the Google account(s).
     * Used when the sign-in screen opens.
     */
    suspend fun requestSavedCredential(): CredentialResult {
        val googleIdOption = GetGoogleIdOption.Builder()
            .setServerClientId(webClientId)
            .setFilterByAuthorizedAccounts(false) // also list accounts not used in this app yet
            .setAutoSelectEnabled(false)
            .build()
        return request(listOf(GetPasswordOption(), googleIdOption), reportNoCredential = false)
    }

    /** The "Sign in with Google" button flow; it can also add a Google account to the device. */
    suspend fun requestGoogleAccount(): CredentialResult {
        val option = GetSignInWithGoogleOption.Builder(webClientId).build()
        return request(listOf(option), reportNoCredential = true)
    }

    /** Tells the credential providers the user signed out. */
    suspend fun clearCredentialState() {
        try {
            credentialManager.clearCredentialState(ClearCredentialStateRequest())
        } catch (e: ClearCredentialException) {
            Log.w(TAG, "Could not clear credential state: ${e.type} ${e.errorMessage}")
        }
    }

    private suspend fun request(
        options: List<CredentialOption>,
        reportNoCredential: Boolean
    ): CredentialResult {
        val request = GetCredentialRequest.Builder()
            .apply { options.forEach { addCredentialOption(it) } }
            .build()

        return try {
            parse(credentialManager.getCredential(context, request))
        } catch (e: GetCredentialCancellationException) {
            CredentialResult.Dismissed
        } catch (e: NoCredentialException) {
            if (reportNoCredential) {
                CredentialResult.Error("No Google account is available on this device")
            } else {
                CredentialResult.Dismissed
            }
        } catch (e: GetCredentialException) {
            Log.w(TAG, "getCredential failed: ${e.type} ${e.errorMessage}")
            CredentialResult.Error(e.errorMessage?.toString() ?: e.type)
        }
    }

    private fun parse(response: GetCredentialResponse): CredentialResult {
        return when (val credential = response.credential) {
            is PasswordCredential ->
                CredentialResult.Password(credential.id, credential.password)

            is CustomCredential -> {
                if (credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                    try {
                        val google = GoogleIdTokenCredential.createFrom(credential.data)
                        CredentialResult.Google(google.idToken)
                    } catch (e: GoogleIdTokenParsingException) {
                        CredentialResult.Error("Invalid Google credential")
                    }
                } else {
                    CredentialResult.Error("Unexpected credential type")
                }
            }

            else -> CredentialResult.Error("Unexpected credential type")
        }
    }

    private companion object {
        const val TAG = "CredentialAuthClient"
    }
}
